package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

/* Build manifest.

   The marketing site is the feature specification: it describes the product we
   intend to sell, including parts that are designed and not yet built. This
   walks the same content the site is generated from and writes the honest
   answer next to it, so the spec and the status can never drift apart.

   Statuses live in content/_status.json, which is small and meant to be edited.
   The generated BUILD-MANIFEST.md is not meant to be edited: it is overwritten
   on every build.
*/

type statusFile struct {
	Pages    map[string]string `json:"pages"`
	Sections map[string]string `json:"sections"`
	Items    map[string]string `json:"items"`
}

const (
	stLive    = "live"
	stPartial = "partial"
	stPlanned = "planned"
	stNA      = "na"
)

func statusLabel(s string) string {
	switch s {
	case stLive:
		return "LIVE"
	case stPartial:
		return "PARTIAL"
	case stPlanned:
		return "PLANNED"
	case stNA:
		return "N/A"
	case "":
		return "UNSET"
	}
	return strings.ToUpper(s)
}

func loadStatus() statusFile {
	var st statusFile
	raw, err := os.ReadFile(filepath.Join(contentIn, "_status.json"))
	if err != nil {
		fail("read _status.json: " + err.Error())
	}
	if err := json.Unmarshal(raw, &st); err != nil {
		fail("parse _status.json: " + err.Error())
	}
	return st
}

// sectionKey is the human editable key for a section: page slug plus its
// heading. Titles are used rather than generated ids because this file is
// maintained by hand.
func sectionKey(slug, title string) string {
	if title == "" {
		return slug + "/*"
	}
	return slug + "/" + strings.TrimSpace(title)
}

func renderManifest() string {
	st := loadStatus()
	var b strings.Builder

	counts := map[string]int{}
	bump := func(s string) { counts[s]++ }

	b.WriteString("# AlphaFlux build manifest\n\n")
	b.WriteString("Generated from `content/*.json` and `content/_status.json` by `go run ./build`. ")
	b.WriteString("Do not edit this file: it is overwritten on every build. Edit the status file instead.\n\n")
	b.WriteString("The site is the specification. This is the answer to whether each part of it exists yet.\n\n")
	b.WriteString("Statuses: **LIVE** works today, **PARTIAL** some of it works, **PLANNED** designed and promised but not built, **N/A** a page or a policy rather than a feature.\n\n")

	// Summary first, so the state of things is one glance.
	var sum []string
	for slug := range bySlug {
		s := st.Pages[slug]
		if s == "" {
			s = stPlanned
		}
		bump(s)
	}
	sum = append(sum,
		fmt.Sprintf("| %s | %d |", statusLabel(stLive), counts[stLive]),
		fmt.Sprintf("| %s | %d |", statusLabel(stPartial), counts[stPartial]),
		fmt.Sprintf("| %s | %d |", statusLabel(stPlanned), counts[stPlanned]),
		fmt.Sprintf("| %s | %d |", statusLabel(stNA), counts[stNA]),
	)
	b.WriteString("| Page status | Pages |\n|---|---|\n")
	for _, r := range sum {
		b.WriteString(r + "\n")
	}
	b.WriteString("\n---\n\n")

	// Then page by page, in rail order.
	for _, slug := range order {
		p := bySlug[slug]
		if p == nil {
			continue
		}
		pageStatus := st.Pages[slug]
		if pageStatus == "" {
			pageStatus = stPlanned
		}
		label := navItem(slug).Label
		if label == "" {
			label = slug
		}
		b.WriteString(fmt.Sprintf("## %s  \n`/%s`  **%s**\n\n", label, urlOf(slug), statusLabel(pageStatus)))

		if p.Stand != "" {
			b.WriteString("> " + p.Stand + "\n\n")
		}

		for _, s := range p.Sections {
			// Skip the sections that are layout rather than claims. A figure is
			// a description of the shape of the product, not a feature that can
			// be built, so listing it as an unticked box is noise.
			switch s.Kind {
			case "hero", "modules", "sitemap", "statement", "figures", "code", "order":
				continue
			}
			secStatus := st.Sections[sectionKey(slug, s.Title)]
			if secStatus == "" {
				secStatus = pageStatus
			}
			bump("s:" + secStatus)

			title := s.Title
			if title == "" {
				title = s.Kind
			}
			b.WriteString(fmt.Sprintf("### %s  \n**%s**\n\n", title, statusLabel(secStatus)))
			if s.Lede != "" {
				b.WriteString(s.Lede + "\n\n")
			}

			var lines []string
			for _, it := range s.Items {
				is := st.Items[sectionKey(slug, it.Title)]
				if is == "" {
					is = secStatus
				}
				bump("i:" + is)
				mark := " "
				if is == stLive {
					mark = "x"
				}
				t := it.Title
				if t == "" {
					continue
				}
				note := it.Text
				if len(note) > 150 {
					note = note[:147] + "..."
				}
				lines = append(lines, fmt.Sprintf("- [%s] **%s** (%s) %s", mark, t, statusLabel(is), note))
			}
			if len(lines) > 0 {
				b.WriteString(strings.Join(lines, "\n") + "\n\n")
			}
		}
	}

	// Roll up the section and item counts so the summary reflects the detail.
	b.WriteString("---\n\n")
	b.WriteString("## Totals\n\n")
	b.WriteString("| Level | LIVE | PARTIAL | PLANNED |\n|---|---|---|---|\n")
	b.WriteString(fmt.Sprintf("| Sections | %d | %d | %d |\n",
		counts["s:"+stLive], counts["s:"+stPartial], counts["s:"+stPlanned]))
	b.WriteString(fmt.Sprintf("| Features | %d | %d | %d |\n",
		counts["i:"+stLive], counts["i:"+stPartial], counts["i:"+stPlanned]))
	b.WriteString("\n")

	// Anything claimed on the site with no status at all is the thing most
	// likely to be forgotten, so call it out rather than defaulting it away.
	b.WriteString("## Status file coverage\n\n")
	b.WriteString(fmt.Sprintf("- Pages listed: %d of %d\n", len(st.Pages), len(bySlug)))
	b.WriteString(fmt.Sprintf("- Section overrides: %d\n", len(st.Sections)))
	b.WriteString(fmt.Sprintf("- Feature overrides: %d\n", len(st.Items)))
	b.WriteString("\nA section or feature with no override inherits the status of its page, so this file only needs ")
	b.WriteString("an entry where something differs from its page.\n")

	return b.String()
}

// manifestNames returns the produced file so the stale pruner knows about it.
func manifestNames() []string { return []string{"BUILD-MANIFEST.md"} }

// sortedStatusKeys is used by the coverage check to keep output stable.
func sortedStatusKeys(m map[string]string) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
